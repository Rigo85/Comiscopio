const fs = require('node:fs');
const path = require('node:path');
const pkg = require('../package.json');
const metadata = {
  name: pkg.build.productName,
  version: pkg.version,
  description: pkg.description,
  author: pkg.author,
  license: pkg.license,
  repositoryUrl: pkg.homepage,
};
const output = '// Generated by scripts/generate-metadata.cjs from package.json.\n' +
  `export const APP_METADATA = ${JSON.stringify(metadata, null, 2)} as const;\n`;
const file = path.join(__dirname, '../shared/app-metadata.ts');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) fs.writeFileSync(file, output);
